/// 把 [PixelGlyphData] 绘制成任意整数倍的像素图标。
class PixelGlyph extends StatelessWidget {
  const PixelGlyph(
    this.data, {
    super.key,
    this.size = 16,
    this.color,
    this.accent,
  });

  final PixelGlyphData data;
  final double size;
  final Color? color;
  final Color? accent;

  @override
  Widget build(BuildContext context) {
    final p = PixelPalette.of(context);
    final accent = this.accent ?? p.gold;
    final main = color ?? p.ink;
    return SizedBox(
      width: size,
      height: size,
      child: CustomPaint(
        isComplex: false,
        painter: _GlyphPainter(
          data,
          main: main,
          accent: accent,
          light: Color.lerp(accent, Colors.white, 0.45)!,
          deep: Color.lerp(accent, Colors.black, 0.32)!,
          shade: main.withValues(alpha: 0.38),
        ),
      ),
    );
  }
}

class _GlyphPainter extends CustomPainter {
  const _GlyphPainter(
    this.data, {
    required this.main,
    required this.accent,
    required this.light,
    required this.deep,
    required this.shade,
  });

  final PixelGlyphData data;
  final Color main;
  final Color accent;
  final Color light;
  final Color deep;
  final Color shade;

  @override
  void paint(Canvas canvas, Size size) {
    final cell = size.shortestSide / 16.0;
    final paint = Paint()..isAntiAlias = false;
    for (var y = 0; y < data.rows.length; y++) {
      final row = data.rows[y];
      for (var x = 0; x < row.length && x < 16; x++) {
        final ch = row[x];
        if (ch == '.') continue;
        paint.color = switch (ch) {
          '#' => main,
          '+' => accent,
          '=' => light,
          '~' => deep,
          '-' => shade,
          _ => const Color(0x00000000),
        };
        if (paint.color.a == 0) continue;
        canvas.drawRect(Rect.fromLTWH(x * cell, y * cell, cell, cell), paint);
      }
    }
  }

  @override
  bool shouldRepaint(_GlyphPainter oldDelegate) =>
      oldDelegate.data != data ||
      oldDelegate.main != main ||
      oldDelegate.accent != accent ||
      oldDelegate.light != light ||
      oldDelegate.deep != deep ||
      oldDelegate.shade != shade;
}
